import { expect, test } from '@playwright/test';
import type { Locator, Page, TestInfo } from '@playwright/test';
import { setRepeatCount } from './repeat-counter';
const button = (page: Page, name: string) => page.getByRole('button', { name, exact: true });
const feedback = (page: Page) => page.locator('.feedback');
const scaffold = (page: Page) => page.getByRole('region', { name: 'Bantuan belajar' });
const press = (info: TestInfo) => (control: Locator) => info.project.name === 'mobile' ? control.tap() : control.click();
const errorsByPage = new WeakMap<Page, string[]>();
test.beforeEach(async ({ page }) => {
  const errors: string[] = []; errorsByPage.set(page, errors);
  page.on('pageerror', (error) => errors.push(error.message));
  page.on('console', (message) => { if (message.type() === 'error') errors.push(message.text()); });
});
test.afterEach(async ({ page }) => expect(errorsByPage.get(page)).toEqual([]));
async function capture(page: Page, info: TestInfo, name: string) {
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(page.viewportSize()!.width);
  for (const control of await page.locator('button:visible, summary:visible, select:visible').all()) {
    const bounds = await control.boundingBox();
    expect(bounds!.width).toBeGreaterThanOrEqual(44); expect(bounds!.height).toBeGreaterThanOrEqual(44);
  }
  await page.screenshot({path:`.verification/idwdyd-${info.project.name}-${name}.png`, fullPage:true});
}

test('automatic placement and Play; genuine guided participation; independent empty tray', async ({ page }, info) => {
  const tap=press(info);
  await page.goto('/');
  await expect(scaffold(page)).toHaveAttribute('data-demo-phase','command');
  await expect(page.locator('.ghost-hand')).toHaveAttribute('data-target','.palette-command[data-type="forward"]');
  await expect(button(page,'Satu langkah')).toHaveCount(0);
  await expect(button(page,'Lihat contoh')).toHaveCount(0);
  await expect(page.locator('.lesson-phase, .demo-trace, .slot-count, .lesson-heading')).toHaveCount(0);
  await expect(scaffold(page)).toHaveAttribute('data-demo-phase','done',{timeout:15000});
  await expect(feedback(page)).toHaveAttribute('data-status','completed');
  await expect(page.locator('.command-block')).toHaveCount(1);
  await expect(page.locator('.ghost-hand')).toHaveCount(0);
  await expect(page.locator('.controls-area, .palette-area')).toHaveCount(0);
  await capture(page,info,'i-do');
  await tap(button(page,'Lanjut'));
  await expect(page.locator('.command-block')).toHaveCount(1);
  await expect(feedback(page)).toHaveAttribute('data-actions','0');
  await expect(page.locator('.ghost-hand')).toHaveAttribute('data-target','.palette-command[data-type="forward"]');
  await page.waitForTimeout(1200);
  await expect(page.locator('.command-block')).toHaveCount(1);
  await capture(page,info,'we-do-place');
  await tap(button(page,'Tambah Maju'));
  await expect(page.locator('.ghost-hand')).toHaveAttribute('data-target','.run-button');
  await expect(page.locator('.palette-area')).toHaveCount(0);
  await expect(button(page,'Satu langkah')).toHaveCount(0);
  await tap(button(page, 'Pilih perintah 2: Maju'));
  await tap(button(page, 'Hapus perintah 2: Maju'));
  await expect(page.locator('.ghost-hand')).toHaveAttribute('data-target','.palette-command[data-type="forward"]');
  await tap(button(page, 'Tambah Maju'));
  await tap(button(page,'Jalankan'));
  await expect(feedback(page)).toHaveAttribute('data-status','completed');
  await tap(button(page,'Lanjut'));
  await expect(scaffold(page)).toHaveAttribute('data-demo-phase','done',{timeout:15000});
  await tap(button(page,'Lanjut'));
  await expect(scaffold(page)).toHaveAttribute('data-phase','independent');
  await expect(page.locator('.command-block')).toHaveCount(0);
  await expect(page.locator('.ghost-hand, .instruction-focus')).toHaveCount(0);
  for(let i=0;i<3;i++) await tap(button(page,'Tambah Maju'));
  await tap(button(page,'Jalankan'));
  await expect(feedback(page)).toHaveAttribute('data-status','completed');
  await capture(page,info,'you-do');
});

test('secondary replay and skip cancel old work; responsive pointer stays on its real target', async ({page},info)=>{
  const tap=press(info);
  await page.goto('/');
  await expect(scaffold(page)).toHaveAttribute('data-demo-phase','done',{timeout:15000});
  await page.locator('summary').click(); await tap(button(page,'Ulang contoh'));
  await expect(scaffold(page)).toHaveAttribute('data-demo-phase','command');
  await page.locator('summary').click(); await tap(button(page,'Lewati contoh'));
  await expect(scaffold(page)).toHaveAttribute('data-demo-phase','skipped');
  await expect(feedback(page)).toHaveAttribute('data-status','idle');
  await page.waitForTimeout(1600);
  await expect(feedback(page)).toHaveAttribute('data-actions','0');
  await tap(button(page,'Lanjut'));
  await page.setViewportSize({width:320,height:740});
  await expect(page.locator('.ghost-hand')).toBeVisible();
  await page.waitForTimeout(800);
  const anchor=await button(page,'Tambah Maju').boundingBox();
  const hand=await page.locator('.ghost-hand').boundingBox();
  expect(hand!.x+29/64*52).toBeGreaterThan(anchor!.x);
  expect(hand!.x+29/64*52).toBeLessThan(anchor!.x+anchor!.width);
  await capture(page,info,'anchored-320');
});

test('turn choice is not supplied; Repeat uses a genuine count choice; debugging introduces Step', async ({page},info)=>{
  const tap=press(info);
  await page.goto('/?level=m2-right-together');
  await tap(button(page,'Tambah di posisi 2'));
  await expect(page.locator('.ghost-hand')).toHaveAttribute('data-target','.palette-commands');
  await expect(button(page,'Tambah Kiri')).toBeVisible(); await expect(button(page,'Tambah Kanan')).toBeVisible();
  await page.waitForTimeout(800);
  const group = await page.locator('.palette-commands').boundingBox();
  const hand = await page.locator('.ghost-hand').boundingBox();
  expect(hand!.x + 29 / 64 * 52).toBeCloseTo(group!.x + group!.width / 2, 0);
  await capture(page, info, 'turn-choice');
  await tap(button(page,'Tambah Kanan')); await tap(button(page,'Tambah Maju')); await tap(button(page,'Jalankan'));
  await expect(feedback(page)).toHaveAttribute('data-status','completed');
  await page.goto('/?level=m2-repeat-watch');
  await expect(scaffold(page)).toHaveAttribute('data-demo-phase','done',{timeout:15000});
  await expect(feedback(page)).toHaveAttribute('data-loop-iteration','2');
  await tap(button(page,'Lanjut')); await tap(button(page,'Pilih Ulangi 1'));
  await expect(page.locator('.ghost-hand')).toHaveAttribute('data-target','[data-count-index="0"]');
  await setRepeatCount(page, 0, 3, tap);
  await tap(button(page,'Jalankan')); await expect(feedback(page)).toHaveAttribute('data-status','completed');
  await page.goto('/?level=m2-debug-watch');
  await expect(scaffold(page)).toHaveAttribute('data-demo-phase','done',{timeout:30000});
  await expect(button(page,'Pilih perintah 2: Kiri')).toBeVisible();
  await page.goto('/?level=m2-debug-together');
  await expect(button(page,'Satu langkah')).toBeVisible();
  await tap(button(page,'Jalankan')); await expect(feedback(page)).toHaveAttribute('data-status','finished');
  await tap(button(page,'Tambah di posisi 4')); await tap(button(page,'Tambah Maju')); await tap(button(page,'Jalankan'));
  await expect(feedback(page)).toHaveAttribute('data-status','completed');
  await capture(page,info,'later-concepts');
});

test('guided mistakes remain observable and editable; a repair returns attention to Play', async ({ page }, info) => {
  const tap = press(info);
  await page.goto('/?level=m2-right-together');
  await tap(button(page, 'Tambah di posisi 2'));
  await tap(button(page, 'Tambah Kiri'));
  await tap(button(page, 'Tambah Maju'));
  await tap(button(page, 'Jalankan'));
  await expect(feedback(page)).toHaveAttribute('data-status', 'failed');
  await expect(page.locator('.failed-command')).toBeVisible();
  await expect(page.locator('.ghost-hand')).toHaveAttribute('data-target', '.editor [data-command-path="2"]');
  await expect(page.locator('.command-block.instruction-focus')).toHaveAttribute('data-command-path', '2');
  await expect(feedback(page)).not.toHaveClass(/instruction-focus/);
  await page.waitForTimeout(800);
  const command = await page.locator('.failed-command').boundingBox();
  const hand = await page.locator('.ghost-hand').boundingBox();
  const fingertip = { x: hand!.x + 29 / 64 * 52, y: hand!.y + 4 / 64 * 52 };
  expect(fingertip.x).toBeGreaterThan(command!.x);
  expect(fingertip.x).toBeLessThan(command!.x + command!.width);
  expect(fingertip.y).toBeGreaterThan(command!.y);
  expect(fingertip.y).toBeLessThan(command!.y + command!.height);
  await capture(page, info, 'guided-mistake');
  await tap(button(page, 'Pilih perintah 2: Kiri'));
  await expect(page.locator('.ghost-hand')).toHaveAttribute('data-target', '.palette-commands');
  await tap(button(page, 'Ganti dengan Kanan'));
  await expect(page.locator('.palette-area, .selection-tools')).toHaveCount(0);
  await expect(page.locator('.ghost-hand')).toHaveAttribute('data-target', '.run-button');
  await tap(button(page, 'Jalankan'));
  await expect(feedback(page)).toHaveAttribute('data-status', 'completed');
  await page.locator('summary').click(); await tap(button(page, 'Mulai ulang'));
  await expect(feedback(page)).toHaveAttribute('data-actions', '0');
  await expect(page.locator('.command-block')).toHaveCount(1);
});

test('reduced motion preserves autoplay, placement, guidance and quiet drawing', async ({page},info)=>{
  const tap=press(info);
  await page.emulateMedia({reducedMotion:'reduce'});
  await page.goto('/');
  await expect(page.locator('.ghost-hand')).toHaveAttribute('data-motion','static');
  expect(await page.locator('.ghost-hand').evaluate(el=>getComputedStyle(el).transitionDuration)).toBe('0s');
  await expect(scaffold(page)).toHaveAttribute('data-demo-phase','done',{timeout:15000});
  await expect(page.locator('canvas')).toHaveAttribute('data-cat-animation','static');
  await tap(button(page,'Lanjut'));
  await page.waitForTimeout(8500);
  await expect(feedback(page)).toHaveAttribute('data-actions','0');
  await expect(page.locator('.command-block')).toHaveCount(1);
  await page.addStyleTag({content:'html {font-size:200%;}'});
  await capture(page,info,'reduced-guidance-zoom');
  await tap(button(page,'Tambah Maju')); await tap(button(page,'Jalankan'));
  await expect(feedback(page)).toHaveAttribute('data-status','completed');
});
